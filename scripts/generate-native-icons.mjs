// 从 @lucide/svelte（原版界面使用的图标库，ISC 许可）提取原生外壳用到的图标，生成 Go 源码。
//
// 用法：node scripts/generate-native-icons.mjs
// 输出：desktop/ui/icons/icons_gen.go（勿手改；增删图标时修改下方列表后重新运行）
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'node_modules/@lucide/svelte/dist/icons');

// 与原版 EditorToolbar / AppTitleBar / ExplorerSidebar / EmptyWorkspace / StatusBar 使用的图标对应。
const names = [
  'bold', 'italic', 'strikethrough', 'underline', 'highlighter', 'code', 'code-xml', 'heading-1',
  'heading-2', 'heading-3', 'pilcrow', 'list', 'list-ordered', 'square-check', 'quote', 'link',
  'table-2', 'minus', 'search', 'list-tree', 'book-open-text', 'file-code', 'panel-left', 'sun',
  'moon', 'settings', 'file-plus', 'folder-open', 'file-text', 'x', 'chevron-down',
  'chevron-right', 'folder', 'plus', 'save', 'refresh-cw', 'replace', 'undo-2', 'redo-2',
  'settings-2', 'palette', 'file-image', 'chart-column', 'sliders-horizontal', 'info',
  // 提示块（原版 calloutTypes.ts）、资源管理器与标签的文件类型（原版 ExplorerSidebar / DocumentTabs）
  'lightbulb', 'star', 'triangle-alert', 'check', 'loader-circle', 'octagon-alert', 'file-json-2', 'file-type-2', 'image', 'keyboard',
  'type', 'upload', 'list-checks', 'zap', 'history', 'file-down', 'columns-2', 'picture-in-picture-2',
  'rotate-ccw', 'download',
  // 折叠块（原版 EditorToolbar 的 PanelTopClose 按钮）
  'panel-top-close',
  // 快捷插入的图表与注释（原版 quickInsert 的 diagram、comment）
  'workflow', 'message-square-text',
  // 表情（原版 EditorToolbar 的 Smile 按钮）
  'smile',
  // Markdown 小窗（原版 AppTitleBar）
  'pin', 'pin-off', 'maximize-2',
];

// 读取图标源：v1 中部分旧名（如 file-json-2）只剩 .js 别名，指向改名后的 .svelte。
function readIcon(name) {
  const svelte = join(iconsDir, `${name}.svelte`);
  if (existsSync(svelte)) return readFileSync(svelte, 'utf8');
  const alias = readFileSync(join(iconsDir, `${name}.js`), 'utf8').match(/from "\.\/([a-z0-9-]+)\.svelte"/);
  if (!alias) throw new Error(`找不到图标 ${name}`);
  return readFileSync(join(iconsDir, `${alias[1]}.svelte`), 'utf8');
}

const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`).join(' ');

let out = `// Code generated by scripts/generate-native-icons.mjs; DO NOT EDIT.
// 图标来自 Lucide（https://lucide.dev），ISC 许可。

package icons

var svgs = map[string]string{
`;
for (const name of names) {
  const src = readIcon(name);
  const m = src.match(/const iconNode = (\[.*\]);/);
  if (!m) throw new Error(`无法解析图标 ${name}`);
  const nodes = JSON.parse(m[1]);
  const body = nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  out += `\t${JSON.stringify(name)}: ${JSON.stringify(svg)},\n`;
}
out += '}\n';
const target = join(root, 'desktop/ui/icons/icons_gen.go');
writeFileSync(target, out);
// 生成结果交给 gofmt 对齐，保证与手写代码同样通过格式检查。
execFileSync('gofmt', ['-w', target]);
console.log(`${names.length} icons`);

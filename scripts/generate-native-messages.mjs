// 从前端的界面文案生成原生外壳的 Go 文案表（计划 D5：文案只维护一处）。
//
// 来源与优先级与 src/app/i18n.ts 的 t() 一致：先 EMOJI_TRANSLATIONS（i18n.emoji.ts），再 EXTRA_TRANSLATIONS，
// 再 inlang 消息；
// 另附 Markdown 检查规则标题（src/lib/markdown-lint/ruleTitles.ts，键为 lintRule.MDxxx）。
// 用法：node scripts/generate-native-messages.mjs
// 输出：desktop/ui/shell/messages_gen.go（勿手改；修改文案后重新运行本脚本）
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const locales = ['zh-CN', 'zh-TW', 'en-US'];

/** 解析 EXTRA_TRANSLATIONS（i18n.ts）或 EMOJI_TRANSLATIONS（i18n.emoji.ts）的某个语言块：`    key: '值',`（值可换行书写；
 * 一行可写多项，如 `    a: '…', b: '…',`）。 */
function extraTranslations(source, locale) {
  const start = source.indexOf(`  '${locale}': {`);
  if (start < 0) throw new Error(`${locale} 翻译块缺失`);
  const end = source.indexOf('\n  },', start);
  const block = source.slice(start, end);
  const table = {};
  const entry = /(?:^ {4}|, )([A-Za-z0-9_]+):\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")/gm;
  for (const m of block.matchAll(entry)) {
    table[m[1]] = JSON.parse(m[2].startsWith("'") ? `"${m[2].slice(1, -1).replace(/\\'/g, "'").replace(/"/g, '\\"')}"` : m[2]);
  }
  return table;
}

function inlangMessages(locale) {
  const raw = JSON.parse(readFileSync(join(root, 'project.inlang/messages', `${locale}.json`), 'utf8'));
  delete raw.$schema;
  return Object.fromEntries(Object.entries(raw).filter(([, v]) => typeof v === 'string'));
}

/** 解析 ruleTitles.ts 的 `const XX_TITLES = { MD001: '…', … }`，键加前缀 lintRule.。 */
function lintRuleTitles(source, name) {
  const start = source.indexOf(`const ${name}:`);
  if (start < 0) throw new Error(`ruleTitles.ts 中没有 ${name}`);
  const block = source.slice(start, source.indexOf('\n};', start));
  const table = {};
  for (const m of block.matchAll(/^ {2}(MD\d{3}): '((?:[^'\\]|\\.)*)'/gm)) {
    table[`lintRule.${m[1]}`] = m[2].replace(/\\'/g, "'");
  }
  return table;
}

const source = readFileSync(join(root, 'src/app/i18n.ts'), 'utf8');
const emojiSource = readFileSync(join(root, 'src/app/i18n.emoji.ts'), 'utf8');
const ruleSource = readFileSync(join(root, 'src/lib/markdown-lint/ruleTitles.ts'), 'utf8');
const ruleTables = { 'zh-CN': 'ZH_CN_TITLES', 'zh-TW': 'ZH_TW_TITLES', 'en-US': 'EN_TITLES' };
const tables = {};
for (const locale of locales) {
  tables[locale] = {
    ...inlangMessages(locale),
    ...extraTranslations(source, locale),
    ...extraTranslations(emojiSource, locale),
    ...lintRuleTitles(ruleSource, ruleTables[locale]),
  };
}

const goString = (s) => JSON.stringify(s);
const goName = { 'zh-CN': 'msgZhCN', 'zh-TW': 'msgZhTW', 'en-US': 'msgEnUS' };
let out = '// Code generated by scripts/generate-native-messages.mjs; DO NOT EDIT.\n\npackage shell\n';
for (const locale of locales) {
  out += `\nvar ${goName[locale]} = map[string]string{\n`;
  for (const key of Object.keys(tables[locale]).sort()) {
    out += `\t${goString(key)}: ${goString(tables[locale][key])},\n`;
  }
  out += '}\n';
}
const target = join(root, 'desktop/ui/shell/messages_gen.go');
writeFileSync(target, out);
// 生成结果交给 gofmt 对齐，保证与手写代码同样通过格式检查。
execFileSync('gofmt', ['-w', target]);
console.log(locales.map((l) => `${l}: ${Object.keys(tables[l]).length}`).join(', '));

// 从前端主题注册表（src/app/services/themeRegistry.ts）生成原生外壳的内置主题（Go 源码）。
//
// 用 Vite 的 SSR 模块加载直接执行原模块，取 createThemeVariant 组装后的最终令牌，不用正则解析 TS。
// 用法：node scripts/generate-native-themes.mjs
// 输出：desktop/ui/themes/builtin_gen.go、导出样式副本 desktop/ui/themes/export_document.css
// （来自 src/app/styles/export-document.css）与 Quick Look 扩展的内置主题表
// desktop/packaging/macos/NomoQuickLookPreview/BuiltinThemes.swift；均勿手改，主题或导出样式变化后重新运行。
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({
  root,
  configFile: false,
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
  // 只做一次性 SSR 加载，关闭依赖预扫描（否则关闭服务器后扫描仍在进行并报错）。
  optimizeDeps: { noDiscovery: true, entries: [] },
});
try {
  const registry = await server.ssrLoadModule('/src/app/services/themeRegistry.ts');
  const types = await server.ssrLoadModule('/src/lib/theme/types.ts');
  const themes = registry.themeRegistry.listThemes().filter((t) => registry.themeRegistry.isBuiltinTheme(t.id));
  const go = (v) => JSON.stringify(v);
  const strMap = (o) =>
    `map[string]string{${Object.keys(o)
      .sort()
      .map((k) => `${go(k)}: ${go(o[k])}`)
      .join(', ')}}`;
  let out = `// Code generated by scripts/generate-native-themes.mjs; DO NOT EDIT.

package themes

// ColorTokenNames 与 src/lib/theme/types.ts 的 THEME_COLOR_TOKEN_NAMES 一致。
var ColorTokenNames = []string{${types.THEME_COLOR_TOKEN_NAMES.map(go).join(', ')}}

// StyleTokenNames 与 THEME_STYLE_TOKEN_NAMES 一致。
var StyleTokenNames = []string{${types.THEME_STYLE_TOKEN_NAMES.map(go).join(', ')}}

// CSSVariables 是令牌到导出 HTML 中 CSS 变量名的映射（THEME_TOKEN_CSS_VARIABLES 与
// THEME_STYLE_TOKEN_CSS_VARIABLES）。
var CSSVariables = ${strMap({ ...registry.THEME_TOKEN_CSS_VARIABLES, ...registry.THEME_STYLE_TOKEN_CSS_VARIABLES })}

// DefaultThemeID 与 DEFAULT_COLOR_THEME_ID 一致。
const DefaultThemeID = ${go(registry.DEFAULT_COLOR_THEME_ID)}

var builtin = []*Theme{
`;
  for (const t of themes) {
    out += `\t{ID: ${go(t.id)}, Version: ${go(t.version)}, Author: ${go(t.author)}, StyleProfile: ${go(t.styleProfile)}, Builtin: true,\n`;
    out += `\t\tNames: ${strMap(t.localizedNames)},\n`;
    out += `\t\tVariants: [2]Variant{\n`;
    for (const scheme of ['light', 'dark']) {
      const v = t.variants[scheme];
      out += `\t\t\t{Tokens: ${strMap(v.tokens)},\n\t\t\t\tStyle: ${strMap(v.styleTokens)},\n\t\t\t\tShiki: ${go(v.shikiTheme)}, Mermaid: ${go(v.mermaid.theme)}},\n`;
    }
    out += `\t\t}},\n`;
  }
  out += '}\n';
  const target = join(root, 'desktop/ui/themes/builtin_gen.go');
  writeFileSync(target, out);
  execFileSync('gofmt', ['-w', target]);
  // Quick Look 扩展只需颜色令牌：以 JSON 字面量嵌入（运行时解析，避免大型字典字面量拖慢 swiftc 类型检查）。
  const qlThemes = Object.fromEntries(
    themes.map((t) => [t.id, { light: t.variants.light.tokens, dark: t.variants.dark.tokens }]),
  );
  writeFileSync(
    join(root, 'desktop/packaging/macos/NomoQuickLookPreview/BuiltinThemes.swift'),
    `// Code generated by scripts/generate-native-themes.mjs; DO NOT EDIT.

/// 内置颜色主题的令牌（主题 ID → light/dark → 令牌名 → CSS 颜色），与主应用的主题注册表一致。
let builtinThemeTokensJSON = ###"${JSON.stringify(qlThemes)}"###

/// 默认颜色主题 ID（DEFAULT_COLOR_THEME_ID）。
let defaultColorThemeID = ${go(registry.DEFAULT_COLOR_THEME_ID)}
`,
  );
  const css = readFileSync(join(root, 'src/app/styles/export-document.css'), 'utf8');
  writeFileSync(
    join(root, 'desktop/ui/themes/export_document.css'),
    `/* Code generated by scripts/generate-native-themes.mjs from src/app/styles/export-document.css; DO NOT EDIT. */\n${css}`,
  );
  console.log(`${themes.length} themes: ${themes.map((t) => t.id).join(', ')}`);
} finally {
  await server.close();
}

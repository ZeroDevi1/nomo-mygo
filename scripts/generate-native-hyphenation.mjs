// 从 hyphenation.en-us（原版精细排版使用的美式英语 Liang 断词模式，见 public/THIRD_PARTY_NOTICES.md）生成 Go 源码，
// 供原生精细排版（desktop/ui/typography）使用；数据原样搬运，不做修改。
//
// 用法：node scripts/generate-native-hyphenation.mjs
// 输出：desktop/ui/typography/hyphen_en_us_gen.go（勿手改）
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const lang = require(join(root, 'node_modules/hyphenation.en-us/lib/en-us.js'));
const sizes = Object.keys(lang.patterns).map(Number).sort((a, b) => a - b);
let out = '// Code generated by scripts/generate-native-hyphenation.mjs from hyphenation.en-us; DO NOT EDIT.\n\n';
out += 'package typography\n\n';
out += `const enUSLeftMin, enUSRightMin = ${lang.leftmin}, ${lang.rightmin}\n\n`;
out += '// enUSPatterns 按模式长度（含数字）分组，每组为定长模式首尾相接的字符串（Hypher 格式）。\n';
out += 'var enUSPatterns = map[int]string{\n';
for (const size of sizes) out += `\t${size}: ${JSON.stringify(lang.patterns[size])},\n`;
out += '}\n';
if (lang.exceptions) out += `\nconst enUSExceptions = ${JSON.stringify(lang.exceptions)}\n`;
writeFileSync(join(root, 'desktop/ui/typography/hyphen_en_us_gen.go'), out);
console.log(`${sizes.length} pattern groups`);
